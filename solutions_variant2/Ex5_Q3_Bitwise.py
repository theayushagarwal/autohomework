x = 10
y = 20
print("x =", x, bin(x), "| y =", y, bin(y))
print("AND        :", x & y, bin(x & y))
print("OR         :", x | y, bin(x | y))
print("XOR        :", x ^ y, bin(x ^ y))
print("NOT x      :", ~x, bin(~x))
print("x Shift L1 :", x << 1, bin(x << 1))
print("x Shift R1 :", x >> 1, bin(x >> 1))
